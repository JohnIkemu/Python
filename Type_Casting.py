# Type Casting : Converting a value from one data type to another
name = "cjricch"
age = 25
score = (7.5)
money = True

print(type(name))
print(type(age))
print(type(score))
print(type(money))


#How to convert a value to different data type

age = float(25)
print(age)

score = int(7.5)
print(score)

money = str(True)
print(money)

name = bool("cjricch")
print(name)